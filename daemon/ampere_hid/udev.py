HEADER = """\
# SPDX-License-Identifier: GPL-2.0-or-later
#
# Generated by `ampere-hid rules`; the product IDs live in ampere_hid/udev.py.
# Changes made here are overwritten by `ampere-hid install --udev`. To add a
# model on your own machine, put a rule into a separate file.
#
# Grants the logged-in user access to the hidraw nodes of supported mice, so
# the companion service can query them without root.
#
# The rules list exact product IDs on purpose: hidraw access to a shared vendor
# ID would also cover keyboards and other devices built on the same chip. For a
# model that is not listed, find its idProduct with `lsusb`.
#
# Install:  ampere-hid install --udev
"""

RULE = (
    'SUBSYSTEM=="hidraw", ATTRS{{idVendor}}=="{vendor:04x}", '
    'ATTRS{{idProduct}}=="{product:04x}", MODE="0660", TAG+="uaccess"'
)


def render_rules():
    parts = [HEADER]
    for title, notes, ids in GROUPS:
        parts.append(f"# --- {title} ---")
        parts.extend(f"# {note}" for note in notes)
        parts.extend(RULE.format(vendor=v, product=p) for v, p in ids)
        parts.append("")
    return "\n".join(parts)


def vendor_ids():
    return {vendor for _, _, ids in GROUPS for vendor, _ in ids}
